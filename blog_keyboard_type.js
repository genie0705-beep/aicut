async function delay(ms) { return new Promise(r => setTimeout(r, ms)); }

async function run() {
  const b = await chromium.connectOverCDP('http://127.0.0.1:9223');
  const ctx = b.contexts()[0];
  const page = await ctx.newPage();
  page.on('dialog', async d => { await d.dismiss().catch(()=>{}); });

  // 새 PostWriteForm 탭 열기
  console.log('📝 새 에디터 탭 열기...');
  await page.goto('https://blog.naver.com/PostWriteForm.naver?blogId=aicut', { waitUntil: 'domcontentloaded', timeout: 15000 });
  await page.waitForTimeout(5000);
  console.log('URL:', page.url());

  // 1. 제목 설정
  console.log('✏️ 제목 설정...');
  const titleOk = await page.evaluate((t) => {
    const editor = window.SmartEditor?._editors?.['blogpc001'];
    if (editor && typeof editor.setDocumentTitle === 'function') {
      editor.setDocumentTitle(t);
      return true;
    }
    return false;
  }, TITLE);
  console.log('제목:', titleOk ? '✅' : '❌');
  await delay(1000);

  // 2. iframe body에 focus 설정 (JS로)
  const focusOk = await page.evaluate(() => {
    const iframe = document.querySelector('iframe[id^="input_buffer"]');
    if (!iframe) return false;
    const doc = iframe.contentDocument || iframe.contentWindow?.document;
    if (!doc) return false;
    const body = doc.querySelector('[contenteditable="true"]');
    if (!body) return false;
    body.focus();
    return true;
  });
  console.log('iframe focus:', focusOk ? '✅' : '❌');
  await delay(500);

  // 3. keyboard.type으로 본문 입력 (delay=2ms, React 상태 동기화)
  console.log('📄 본문 입력 중 (keyboard.type, 2315자)...');
  const startTime = Date.now();
  await page.keyboard.type(BODY_TEXT, { delay: 2 });
  const elapsed = Math.round((Date.now() - startTime) / 1000);
  console.log(`✅ 본문 입력 완료 (${elapsed}초)`);
  await delay(2000);

  // 4. 센터 정렬 적용 (DOM 직접 수정 - 6/20 검증 완료)
  console.log('🎯 센터 정렬 적용...');
  const centerResult = await page.evaluate(() => {
    const iframe = document.querySelector('iframe[id^="input_buffer"]');
    if (!iframe) return 'iframe 없음';
    const doc = iframe.contentDocument || iframe.contentWindow?.document;
    if (!doc) return 'doc 없음';
    const paragraphs = doc.querySelectorAll('p');
    let count = 0;
    paragraphs.forEach(p => {
      if (p.textContent.trim().length > 0) {
        p.style.textAlign = 'center';
        count++;
      }
    });
    return `${count}개 paragraph center 정렬 완료`;
  });
  console.log('센터정렬:', centerResult);
  await delay(1000);

  // 5. 저장
  console.log('💾 저장...');
  const saveOk = await page.evaluate(() => {
    const btns = document.querySelectorAll('button');
    for (const btn of btns) {
      if (btn.textContent.trim() === '저장') {
        btn.click();
        return true;
      }
    }
    return false;
  });
  console.log('저장:', saveOk ? '✅' : '❌');
  await delay(4000);

  // 6. 저장 확인 + SEO 분석
  const result = await page.evaluate(() => {
    const editor = window.SmartEditor?._editors?.['blogpc001'];
    if (!editor) return { error: 'editor 없음' };

    const data = editor.getDocumentData();
    const comps = data.document.components;
    
    // 분석
    let h2Count = 0, boldCount = 0, centerCount = 0, imgCount = 0;
    let totalParagraphs = 0;
    let totalLen = 0;
    
    for (const comp of comps) {
      if (comp['@ctype'] === 'text') {
        for (const p of (comp.value || [])) {
          totalParagraphs++;
          if (p.type === 'header2' || p.tagName === 'h2') h2Count++;
          if (p.textAlign === 'center') centerCount++;
          for (const node of (p.nodes || [])) {
            if (node.bold) boldCount++;
            totalLen += (node.value || '').length;
          }
        }
      }
      if (comp['@ctype'] === 'image') imgCount++;
    }
    
    // title 확인
    const title = editor.getDocumentTitle ? editor.getDocumentTitle() : '';
    
    return {
      title,
      totalParagraphs,
      h2Count,
      boldCount,
      centerCount,
      imgCount,
      textLen: totalLen
    };
  });
  
  console.log('\n=== 저장 후 SEO 분석 ===');
  console.log(JSON.stringify(result, null, 2));

  if (result.h2Count === 0) {
    console.log('\n⚠️ H2 미적용 - SmartEditor 한계로 자동 H2 전환 불가');
    console.log('   해결: setDocumentData + 발행 방식 시도');
  }

  await b.close();
}
run().catch(e => console.error('❌ 실패:', e.message));
