const IMG_FILES = [
  'aicut_blog_startup_thumb.png',
  'aicut_blog_startup_problem.png',
  'aicut_blog_startup_compare.png',
  'aicut_blog_startup_insight.png',
  'aicut_blog_startup_cta.png'
];

async function run() {
  const cdpPort = process.env.CDP_PORT || 9223;
  const browser = await chromium.connectOverCDP(`http://127.0.0.1:${cdpPort}`);
  const ctx = browser.contexts()[0];
  const page = await ctx.newPage();

  // 1. 네이버 블로그 글쓰기 페이지
  console.log('📝 블로그 에디터 접속 중...');
  await page.goto('https://blog.naver.com/aicut/223538774318?seoRedirect=true', { waitUntil: 'domcontentloaded', timeout: 15000 });
  await page.waitForTimeout(2000);

  // 새 글 작성 페이지로 이동 (글쓰기)
  await page.goto('https://blog.naver.com/blog/write?categoryNo=1', { waitUntil: 'domcontentloaded', timeout: 15000 });
  await page.waitForTimeout(3000);

  console.log('현재 URL:', page.url());

  // 2. 제목 설정
  console.log('✏️ 제목 설정 중...');
  const setTitle = await page.evaluate((t) => {
    const editor = window.SmartEditor?._editors?.['blogpc001'];
    if (editor && typeof editor.setDocumentTitle === 'function') {
      editor.setDocumentTitle(t);
      return true;
    }
    // SE4 방식
    const titleInput = document.querySelector('input._titleInput, input.se4_title_input, input[placeholder*="제목"]');
    if (titleInput) {
      titleInput.value = t;
      titleInput.dispatchEvent(new Event('input', { bubbles: true }));
      return true;
    }
    return false;
  }, TITLE);
  console.log('제목 설정:', setTitle ? '✅' : '❌');
  await page.waitForTimeout(1000);

  // 3. 본문 입력 - clipboard writeText + Ctrl+V
  console.log('📄 본문 입력 중...');
  try {
    await page.evaluate((text) => {
      return navigator.clipboard.writeText(text);
    }, BODY);
    await page.waitForTimeout(500);

    // 에디터 iframe 찾아서 focus
    const focused = await page.evaluate(() => {
      const iframe = document.querySelector('iframe.se2_inputarea, iframe#main, iframe[title*="에디터"]');
      if (iframe) {
        iframe.contentWindow.focus();
        return true;
      }
      // SE4 직접 클릭
      const editorArea = document.querySelector('.se2_inputarea, .se_textarea, [contenteditable="true"]');
      if (editorArea) {
        editorArea.focus();
        return true;
      }
      return false;
    });
    console.log('에디터 focus:', focused ? '✅' : '❌');

    await page.waitForTimeout(500);

    // Ctrl+V
    await page.keyboard.press('Control+V');
    await page.waitForTimeout(3000);
    console.log('붙여넣기 완료');

  } catch (e) {
    console.log('클립보드 실패:', e.message);
  }

  await page.waitForTimeout(2000);

  // 4. 이미지 등록 시도
  console.log('🖼️ 이미지 등록 중...');
  const workspace = 'C:\\Users\\paul\\.openclaw\\workspace';
  for (let i = 0; i < IMG_FILES.length; i++) {
    console.log(`  이미지 ${i+1}/${IMG_FILES.length}: ${IMG_FILES[i]}`);
    
    // 사진 버튼 찾기
    const btnClicked = await page.evaluate(() => {
      // 여러 버튼 셀렉터 시도
      const selectors = [
        'button[aria-label="사진"]',
        'button.se2_image_button',
        'button._uploadBtn',
        'button[data-action="image"]',
        '.se2_photo',
        'a.se2_icon_image',
        'button:has(svg)',
        'button:has-text("사진")',
        'button.media_button'
      ];
      for (const sel of selectors) {
        const btn = document.querySelector(sel);
        if (btn) {
          btn.click();
          return sel;
        }
      }
      return null;
    });
    console.log(`  사진 버튼 클릭: ${btnClicked || '실패'}`);

    await page.waitForTimeout(2000);

    // filechooser 이벤트 대기
    const [fileChooser] = await Promise.all([
      page.waitForEvent('filechooser', { timeout: 5000 }).catch(() => null),
      page.waitForTimeout(1000)
    ]);

    if (fileChooser) {
      const fullPath = `${workspace}\\${IMG_FILES[i]}`;
      await fileChooser.setFiles([fullPath]);
      console.log(`  ✅ 파일 선택 완료: ${IMG_FILES[i]}`);
      await page.waitForTimeout(3000);
    } else {
      console.log(`  ❌ filechooser 이벤트 발생 안 함 (직접 등록 필요)`);
    }
  }

  // 5. 해시태그 입력
  console.log('🏷️ 해시태그 입력 중...');
  const hashResult = await page.evaluate(() => {
    // 발행 패널 해시태그 input 찾기
    const selectors = [
      'input[placeholder*="태그"]',
      'input.tag_input',
      '#tagSearchInput',
      'input._tagSearchInput',
      '.se2_tag_area input'
    ];
    for (const sel of selectors) {
      const input = document.querySelector(sel);
      if (input) {
        input.value = '';
        return true;
      }
    }
    // 발행 패널 열기
    const pubBtns = document.querySelectorAll('button');
    for (const btn of pubBtns) {
      if (btn.textContent.includes('발행') || btn.textContent.includes('등록')) {
        btn.click();
        return '발행패널 열림';
      }
    }
    return false;
  });
  console.log('해시태그 준비:', hashResult);

  await page.waitForTimeout(2000);

  // 6. 저장 버튼 클릭
  console.log('💾 저장 중...');
  const saved = await page.evaluate(() => {
    const btns = document.querySelectorAll('button, a');
    for (const btn of btns) {
      if (btn.textContent.trim() === '저장') {
        btn.click();
        return true;
      }
    }
    return false;
  });
  console.log('저장:', saved ? '✅ 클릭됨' : '❌ 찾을 수 없음');

  await page.waitForTimeout(3000);

  // 7. 저장 확인 (토스트 메시지)
  const toast = await page.evaluate(() => {
    const all = document.body.innerText;
    if (all.includes('저장') && (all.includes('완료') || all.includes('되었') || all.includes('성공'))) {
      return all.substring(0, 200);
    }
    return null;
  });
  console.log('저장 확인:', toast || '토스트 미확인');

  console.log('\n✅ 블로그 작성 프로세스 완료');
  console.log('📸 이미지 파일 목록:');
  IMG_FILES.forEach(f => console.log(`  - ${f}`));

  await browser.close();
}

run().catch(e => {
  console.error('❌ 실패:', e.message);
  process.exit(1);
});
