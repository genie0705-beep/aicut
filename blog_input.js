async function sleep(ms) { return new Promise(r => setTimeout(r, ms)); }

(async () => {
  const b = await chromium.connectOverCDP('http://127.0.0.1:9222');
  const ctx = b.contexts()[0];
  const pages = ctx.pages();
  let page = pages.find(p => p.url().includes('PostWriteForm'));
  
  if (!page) {
    console.log('에디터 탭 없음. 새로 열기...');
    page = await ctx.newPage();
    await page.goto('https://blog.naver.com/PostWriteForm.naver?blogId=aicut', { waitUntil: 'domcontentloaded', timeout: 20000 });
    await sleep(5000);
  }

  console.log('에디터 탭:', page.url());
  await sleep(2000);

  // 제목 입력
  const titleSel = '.se-title-text';
  await page.waitForSelector(titleSel, { timeout: 10000 });
  await page.click(titleSel);
  await sleep(500);
  await page.keyboard.press('Control+A');
  await page.keyboard.type(TITLE, { delay: 20 });
  console.log('제목 입력 완료');

  // 본문 클릭 (제목 아래 영역)
  await page.keyboard.press('Tab');
  await sleep(500);

  // 본문 입력 — 줄바꿈 처리
  const lines = BODY.split('\n');
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (line.length > 0) {
      await page.keyboard.type(line, { delay: 10 });
    }
    if (i < lines.length - 1) {
      await page.keyboard.press('Enter');
      await sleep(30);
    }
  }

  console.log('본문 입력 완료');
  await sleep(1000);

  // 저장
  const saveBtn = await page.$('button.publish_btn__QdaHY, button[class*="save"], .se-save-btn');
  if (saveBtn) {
    await saveBtn.click();
    console.log('임시저장 클릭');
  } else {
    await page.keyboard.press('Control+S');
    console.log('Ctrl+S 저장');
  }

  await sleep(2000);
  console.log('✅ 완료');
  await b.close();
})().catch(e => {
  console.error('Error:', e.message);
  process.exit(1);
}).finally(() => setTimeout(() => process.exit(0), 2000));
